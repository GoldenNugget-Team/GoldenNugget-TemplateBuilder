#!/usr/bin/env python3
"""Write batter_builder/known_keys_data.py from GoldenNugget's tweak registry.

    python tools/make_known_keys.py /path/to/GoldenNugget

The key table suggests these keys for the file a write targets: every plist
key GoldenNugget's own tweaks write (src/tweaks/registry.py), with its type,
the value the tweak writes, its title and description, and their Russian
translations from GoldenNugget's .ts files. Run it again when GoldenNugget
adds tweaks; tests/test_goldennugget.py fails while the file is out of date.
"""
import subprocess
import sys
import xml.etree.ElementTree as ElementTree
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / "batter_builder" / "known_keys_data.py"


def russian(root: Path) -> dict:
    """English -> Russian for GoldenNugget's "Nugget" context; the local UI
    catalog wins over the crowdsourced one, as in the app."""
    table = {}
    for name in ("Nugget_ru.ts", "GoldenNuggetUI_ru.ts"):
        path = root / "src" / "qt" / "translations" / name
        if not path.exists():
            continue
        for context in ElementTree.parse(path).getroot().iter("context"):
            if context.findtext("name") != "Nugget":
                continue
            for message in context.iter("message"):
                source, translation = message.find("source"), message.find("translation")
                if source is None or translation is None or translation.get("type") in ("unfinished", "obsolete"):
                    continue
                if source.text and translation.text:
                    table[source.text] = translation.text
    return table


def type_name(value) -> str:
    if isinstance(value, bool):
        return "Boolean"
    if isinstance(value, int):
        return "Integer"
    if isinstance(value, float):
        return "Real"
    if isinstance(value, (list, dict)):
        return "Array / Dictionary (JSON)"
    return "String"


def build(root: Path) -> dict:
    sys.path.insert(0, str(root))
    from PySide6.QtCore import QCoreApplication
    QCoreApplication.instance() or QCoreApplication([])
    from src.tweaks import registry
    ru = russian(root)
    paths = {}

    def add(path, key, value, spec):
        entry = {"type": type_name(value), "value": value, "title": spec.title,
                 "description": spec.description or ""}
        for field in ("title", "description"):
            if entry[field] in ru:
                entry[field + "_ru"] = ru[entry[field]]
        for field in ("min_version", "max_version"):
            if getattr(spec, field):
                entry[field] = getattr(spec, field)
        if spec.kind is registry.Kind.NUMBER:
            entry.update(min=spec.min_value, max=spec.max_value, step=spec.step)
        paths.setdefault(path, {}).setdefault(key, entry)

    for spec in registry.SPECS:
        if spec.disabled:
            continue
        if spec.factory is not None:
            tweak = spec.factory()
            location = getattr(tweak, "file_location", spec.location)
            values = getattr(tweak, "keyValues", None)
            if isinstance(values, dict):
                for key, value in values.items():
                    add(location.value, key, value, spec)
                continue
        if spec.key:
            value = spec.value
            if spec.kind is registry.Kind.TEXT and not isinstance(value, str):
                value = ""
            add(spec.location.value, spec.key, value, spec)
    commit = subprocess.run(["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True).stdout.strip()
    return {"source": f"GoldenNugget src/tweaks/registry.py {commit}".strip(),
            "paths": {path: dict(sorted(keys.items())) for path, keys in sorted(paths.items())}}


def dumps(data: dict) -> str:
    # a module rather than JSON, so PyInstaller bundles it like any code;
    # one line per key keeps diffs readable
    lines = ['"""Plist keys GoldenNugget\'s own tweaks write, per file. Generated by',
             'tools/make_known_keys.py; do not edit by hand."""', "",
             f"SOURCE = {data['source']!r}", "", "PATHS = {"]
    for path, keys in data["paths"].items():
        lines.append(f"    {path!r}: {{")
        lines += [f"        {key!r}: {entry!r}," for key, entry in keys.items()]
        lines.append("    },")
    return "\n".join(lines + ["}", ""])


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = build(Path(sys.argv[1]).resolve())
    OUTPUT.write_text(dumps(data), encoding="utf-8")
    print(f"{OUTPUT}: {sum(len(keys) for keys in data['paths'].values())} keys in {len(data['paths'])} files")


if __name__ == "__main__":
    main()
